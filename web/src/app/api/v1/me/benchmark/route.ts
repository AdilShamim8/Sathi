import { NextRequest } from "next/server";
import { userIdFromRequest, buildEvidence, ok, unauthorized } from "@/lib/server/sathiApi";
import { getRiskModel } from "@/lib/engine/ml";
import { getForecaster } from "@/lib/engine/forecaster";
import evalJson from "@/data/eval.json";
import benchmarkJson from "@/data/benchmark.json";

export const dynamic = "force-dynamic";

/**
 * Model benchmark (reference: GET /v1/me/benchmark, ML handoff 624d398:
 * "remove hard-coded benchmark metrics; derive benchmark and eval report
 * from eval.json").
 *
 * Every number below is read from docs/metrics/eval.json + benchmark.json,
 * which are generated ONLY by `python -m ml.evaluate` (the `ml/` pipeline) on the
 * frozen held-out test users â€” nothing here is typed by hand, so this route
 * cannot drift from the evaluation. The in-product risk-classifier
 * validation (leakage-safe logistic regression vs the simple rule) is kept
 * as a clearly-labelled second block.
 */
export async function GET(req: NextRequest) {
  try {
    if (!userIdFromRequest(req)) return unauthorized();
    const { metrics } = getRiskModel();
    const fc = getForecaster();
    const evalData = evalJson as Record<string, unknown>;
    const bench = benchmarkJson as Record<string, unknown>;

    const data = {
      title: bench.title,
      description: (bench.description as string) +
        " Served verbatim from the generated artifacts; SIMULATED data only.",
      model_version: fc ? fc.version : (evalData.model_version as string),
      simulated: evalData.label,
      brier_score: bench.brier_score,
      quantile_loss: bench.quantile_loss,
      wape_accuracy: bench.wape_accuracy,
      early_warning_7d: bench.early_warning_7d,
      interpretability: bench.interpretability,
      evaluation: {
        n_test_users: evalData.n_test_users,
        forecast_table_t1: (evalData.forecast as Record<string, unknown>)?.table,
        shortfall_early_warning_t2: evalData.shortfall,
        fairness_audit_t3: {
          per_persona: (evalData.shortfall as Record<string, unknown>)?.per_persona,
          per_income_band: (evalData.shortfall as Record<string, unknown>)?.per_income_band,
          coverage_per_persona: (evalData.shortfall as Record<string, unknown>)?.coverage_per_persona,
        },
        robustness_t4: evalData.robustness,
        ablations_t5: evalData.ablations,
        goal_planner_backtest_t6: evalData.planner_backtest,
        explainability_shap_t7: evalData.shap,
        report: "docs/eval_report.md (generated by python -m ml.evaluate)",
      },
      in_app_classifier_validation: {
        description:
          "Separate in-product model: the shortfall-risk classifier (logistic regression, leakage-safe user-level splits) against the simple rule baseline on this app's synthetic population. Powers the Insights screen's Model health card.",
        brier_score: {
          ml_model: metrics.ml.brier,
          naive_rule_baseline: metrics.ruleBaseline.brier,
          climatology_baseline: metrics.climatology.brier,
          brier_skill_score: metrics.brierSkillScoreVsRule,
          brier_skill_percentage_display: `${metrics.brierSkillScoreVsRule >= 0 ? "+" : ""}${Math.round(metrics.brierSkillScoreVsRule * 1000) / 10}%`,
        },
        pr_auc: { ml_model: metrics.ml.prAuc, naive_rule_baseline: metrics.ruleBaseline.prAuc },
        roc_auc: { ml_model: metrics.ml.auc, naive_rule_baseline: metrics.ruleBaseline.auc },
        reliability: metrics.ml.reliability.map((b) => ({
          bin_lo: b.lo,
          bin_hi: b.hi,
          n: b.n,
          mean_predicted: b.meanPred,
          observed_rate: b.obsRate,
        })),
        trained_on: metrics.trainedOn,
        tested_on: metrics.testedOn,
        baseline_description: metrics.ruleBaseline.description,
      },
      early_warning: {
        lead_days: 7,
        note: "Alerts fire when P(shortfall) crosses the watch band up to 7 days before the trough.",
      },
    };

    const evidence = buildEvidence({
      nTransactions: metrics.testedOn.days,
      windowStart: "frozen held-out test users (never trained/tuned on)",
      asOfDate: new Date().toISOString().slice(0, 10),
      labels: {
        brier_score: "Data",
        quantile_loss: "Data",
        early_warning_7d: "Data",
        evaluation: "Data",
        in_app_classifier_validation: "Data",
      },
      forecastVersion: fc?.version,
    });
    return ok(data, evidence);
  } catch (e) {
    console.error("[v1 benchmark]", e);
    return ok({ error: "benchmark unavailable" }, buildEvidence({
      nTransactions: 0, windowStart: "-", asOfDate: new Date().toISOString().slice(0, 10), labels: {},
    }));
  }
}

